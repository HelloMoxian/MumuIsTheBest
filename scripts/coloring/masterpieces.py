class Painting(Kit):
    def person(self,x,y,w,h,dress=False,hat=False,face=True):
        # Head, neck, torso, arms, lower body all remain editable.
        if dress:self.t(x,y+h*.32,w,h*.65)
        else:
            self.r(x+w*.25,y+h*.35,w*.5,h*.34)
            self.r(x+w*.27,y+h*.65,w*.18,h*.35,-4)
            self.r(x+w*.56,y+h*.65,w*.18,h*.35,4)
        self.bar(x+w*.3,y+h*.4,x+w*.1,y+h*.64,w*.12)
        self.bar(x+w*.7,y+h*.4,x+w*.88,y+h*.59,w*.12)
        self.r(x+w*.42,y+h*.24,w*.16,h*.13)
        self.o(x+w*.27,y,w*.46,h*.29)
        if face:
            self.o(x+w*.38,y+h*.12,max(4,w*.035),max(4,h*.02))
            self.o(x+w*.57,y+h*.12,max(4,w*.035),max(4,h*.02))
            self.o(x+w*.44,y+h*.2,w*.14,max(4,h*.015))
        if hat:self.o(x+w*.12,y-h*.015,w*.76,h*.09);self.r(x+w*.3,y-h*.08,w*.4,h*.09)

    def flower(self,x,y,size,petals=7):
        for n in range(petals):
            a=n*math.tau/petals
            self.o(x+math.sin(a)*size*.34-size*.15,y+math.cos(a)*size*.34-size*.23,size*.3,size*.46,-n*360/petals)
        self.o(x-size*.22,y-size*.22,size*.44)

    def tree(self,x,y,w,h):
        self.r(x+w*.44,y+h*.28,w*.12,h*.72)
        self.o(x,y,w,h*.48);self.o(x-w*.12,y+h*.23,w*.7,h*.28);self.o(x+w*.44,y+h*.18,w*.7,h*.32)

    def house(self,x,y,w,h):
        self.r(x,y+h*.28,w,h*.72);self.t(x-w*.08,y,w*1.16,h*.3)
        self.r(x+w*.41,y+h*.64,w*.2,h*.36)
        for dx in [.13,.68]:self.r(x+w*dx,y+h*.43,w*.18,h*.17)

    def boat(self,x,y,w,h,sail=False):
        self.o(x,y+h*.64,w,h*.32)
        if sail:self.r(x+w*.49,y,w*.025,h*.73);self.t(x+w*.05,y,w*.43,h*.61);self.t(x+w*.54,y+h*.17,w*.4,h*.44)
        else:self.bar(x+w*.42,y+h*.48,x+w*.77,y+h*.89,7)

    def hills(self,y=460):
        self.o(65,y,460,150);self.o(430,y-45,490,195)

    def leaf(self,x,y,w,h,a=0):self.o(x,y,w,h,a)


